static void rgb_to_yuv_clut(unsigned char r, unsigned char g, unsigned char b,
    amba_draw_clut_t *c)
{
  float tmp;

  c->y = (unsigned char)(0.257f * r + 0.504f * g + 0.098f * b + 16);
  tmp = 0.439f * b - 0.291f * g - 0.148f * r + 128;
  if (tmp < 0.0f)
    c->u = 0;
  else if (tmp > 255.0f)
    c->u = 255;
  else
    c->u = (unsigned char)tmp;
  tmp = 0.439f * r - 0.368f * g - 0.071f * b + 128;
  if (tmp < 0.0f)
    c->v = 0;
  else if (tmp > 255.0f)
    c->v = 255;
  else
    c->v = (unsigned char)tmp;
  c->a = 255;
}

void drawdatagen_depth_init_clut(amba_draw_clut_t *clut)
{
  const uint8_t *color_r = depth_color_table + 256 * 0;
  const uint8_t *color_g = depth_color_table + 256 * 1;
  const uint8_t *color_b = depth_color_table + 256 * 2;
  int i;

  if (!clut)
    return;

  memset(clut, 0, OVERLAY_CLUT_SIZE);
  clut[AMBA_DRAW_CLUT_ENTRY_BACKGROUND].v = 128;
  clut[AMBA_DRAW_CLUT_ENTRY_BACKGROUND].u = 128;
  clut[AMBA_DRAW_CLUT_ENTRY_BACKGROUND].y = 235;
  clut[AMBA_DRAW_CLUT_ENTRY_BACKGROUND].a = 0;

  clut[0].y = 0;
  clut[0].u = 128;
  clut[0].v = 128;
  clut[0].a = 0;

  for (i = 1; i < 256; i++) {
    rgb_to_yuv_clut(color_r[i], color_g[i], color_b[i], &clut[i]);
  }
}

void drawdatagen_depth_build_pixel_lut(uint32_t *lut, int draw_format,
    const amba_draw_clut_t *clut)
{
  int i;

  if (!lut || !clut)
    return;

  lut[0] = 0;
  for (i = 1; i < 256; i++) {
    lut[i] = drawdatagen_yuv_clut_to_pixel(&clut[i], draw_format);
  }
}

void drawdatagen_depth_gray8_to_clut(const uint8_t *gray8_src, int src_width, int src_height,
    int src_stride, unsigned char *data_buf, size_t area_pitch, int roi_x, int roi_y,
    int roi_width, int roi_height)
{
  int x, y;

  if (!gray8_src || !data_buf || roi_width <= 0 || roi_height <= 0)
    return;

  for (y = 0; y < roi_height; y++) {
    int sy = roi_y + y;
    if (sy >= src_height)
      sy = src_height - 1;
    if (sy < 0)
      sy = 0;
    for (x = 0; x < roi_width; x++) {
      int sx = roi_x + x;
      if (sx >= src_width)
        sx = src_width - 1;
      if (sx < 0)
        sx = 0;
      uint8_t v = gray8_src[sy * src_stride + sx];
      data_buf[y * area_pitch + x] = (v == 0) ?
          AMBA_DRAW_CLUT_ENTRY_BACKGROUND : (unsigned char)v;
    }
    for (x = roi_width; x < (int)area_pitch; x++) {
      data_buf[y * area_pitch + x] = AMBA_DRAW_CLUT_ENTRY_BACKGROUND;
    }
  }
}

void drawdatagen_depth_gray8_to_pixels(const uint8_t *gray8_src, int src_width, int src_height,
    int src_stride, unsigned char *data_buf, size_t area_pitch, int roi_x, int roi_y,
    int roi_width, int roi_height, int draw_format, int draw_pix_size,
    const uint32_t *lut)
{
  int x, y;

  if (!gray8_src || !data_buf || !lut || roi_width <= 0 || roi_height <= 0)
    return;

  drawdatagen_fill_background(data_buf, roi_height, area_pitch, draw_format);

  if (draw_pix_size == 2) {
    for (y = 0; y < roi_height; y++) {
      int sy = roi_y + y;
      if (sy >= src_height)
        sy = src_height - 1;
      if (sy < 0)
        sy = 0;
      uint16_t *row = (uint16_t *)(data_buf + y * area_pitch);
      for (x = 0; x < roi_width; x++) {
        int sx = roi_x + x;
        if (sx >= src_width)
          sx = src_width - 1;
        if (sx < 0)
          sx = 0;
        uint8_t v = gray8_src[sy * src_stride + sx];
        if (v != 0)
          row[x] = (uint16_t)lut[v];
      }
    }
  } else if (draw_pix_size == 4) {
    for (y = 0; y < roi_height; y++) {
      int sy = roi_y + y;
      if (sy >= src_height)
        sy = src_height - 1;
      if (sy < 0)
        sy = 0;
      uint32_t *row = (uint32_t *)(data_buf + y * area_pitch);
      for (x = 0; x < roi_width; x++) {
        int sx = roi_x + x;
        if (sx >= src_width)
          sx = src_width - 1;
        if (sx < 0)
          sx = 0;
        uint8_t v = gray8_src[sy * src_stride + sx];
        if (v != 0)
          row[x] = lut[v];
      }
    }
  }
}
